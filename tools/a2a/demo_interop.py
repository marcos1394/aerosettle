"""Offline independent A2A SDK client discovers Conatus's signed well-known card."""
from __future__ import annotations

import hashlib
from http.server import ThreadingHTTPServer
import json
from pathlib import Path
import tempfile
import threading
import urllib.error
import urllib.request

from a2a.client import ClientFactory
from a2a.types import AgentCard
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from google.protobuf.json_format import ParseDict

from .cards import (b58encode, canonical, generate_card, identity_params,
                    negotiate, public_bytes, verify_conatus_card)
from .catalog import CardCatalog
from .service import handler_for

HOST = "agent.conatus.example.test"


def demonstrate() -> dict:
    owner = Ed25519PrivateKey.generate()
    publisher = Ed25519PrivateKey.generate()
    agent = {"agent_account": b58encode(b"a" * 32), "agent_id": "11" * 32,
             "owner": b58encode(public_bytes(owner)),
             "signing_authority": b58encode(b"b" * 32), "status": "Active",
             "active": True, "capabilities": (1 << 0) | (1 << 5),
             "network": "offline-fixture", "genesis_hash": b58encode(b"c" * 32),
             "program_id": b58encode(b"d" * 32)}
    card = generate_card(agent, owner_private=owner, publisher_private=publisher,
        endpoint=f"https://{HOST}/.well-known/agent-card.json", name="Conatus Discovery Fixture",
        description="Offline registered capability fixture.")
    with tempfile.TemporaryDirectory() as folder:
        catalog = CardCatalog(Path(folder) / "cards.sqlite", lambda _: dict(agent))
        try:
            catalog.publish(card)
            server = ThreadingHTTPServer(("127.0.0.1", 0), handler_for(catalog))
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            try:
                request = urllib.request.Request(
                    f"http://127.0.0.1:{server.server_port}/.well-known/agent-card.json",
                    headers={"Host": HOST, "Accept": "application/json"})
                with urllib.request.urlopen(request, timeout=3) as response:
                    fetched = json.loads(response.read())
                # This model is generated by the independently maintained A2A SDK.
                independent = ParseDict(fetched, AgentCard(), ignore_unknown_fields=False)
                if independent.name != "Conatus Discovery Fixture":
                    raise AssertionError("Independent A2A SDK did not parse the card")
                verified = verify_conatus_card(fetched, agent)
                selected = negotiate(fetched, trusted=True)
                if selected["status"] != "SUPPORTED" or selected["is_executable"]:
                    raise AssertionError("Discovery-only interface negotiation failed")
                try:
                    ClientFactory().create(independent)
                except ValueError as exc:
                    if "no compatible transports" not in str(exc):
                        raise
                else:
                    raise AssertionError("A standard task client accepted a discovery-only binding")
                binding_path = selected["interface"]["url"].split(HOST, 1)[1]
                binding_request = urllib.request.Request(
                    f"http://127.0.0.1:{server.server_port}{binding_path}",
                    headers={"Host": HOST, "Accept": "application/json"})
                with urllib.request.urlopen(binding_request, timeout=3) as response:
                    if json.loads(response.read()) != fetched:
                        raise AssertionError("Custom GET binding returned a different card")
                task_request = urllib.request.Request(
                    f"http://127.0.0.1:{server.server_port}{binding_path}",
                    data=b"{}", headers={"Host": HOST, "Content-Type": "application/json"})
                try:
                    urllib.request.urlopen(task_request, timeout=3)
                except urllib.error.HTTPError as exc:
                    if exc.code != 405:
                        raise AssertionError("Custom binding did not reject POST") from exc
                else:
                    raise AssertionError("Custom binding accepted a POST")
                return {"schema": "A2A AgentCard 1.0", "sdk": "a2a-sdk 1.3.0",
                        "well_known": "/.well-known/agent-card.json",
                        "card_sha256": hashlib.sha256(canonical(fetched)).hexdigest(),
                        "card_id": identity_params(fetched)["cardId"],
                        "verification_status": verified["status"],
                        "selected_binding": selected["interface"]["protocolBinding"],
                        "standard_client_status": "UNSUPPORTED_TRANSPORT",
                        "binding_get_verified": True,
                        "binding_post_status": 405,
                        "skills": selected["skills"], "is_executable": False,
                        "is_financial_authority": False,
                        "funds_transferred": False}
            finally:
                server.shutdown()
                server.server_close()
                thread.join(timeout=3)
        finally:
            catalog.close()


if __name__ == "__main__":
    print(json.dumps(demonstrate(), sort_keys=True))
